    private fun buildActivity(
        id: String,
        title: String,
        description: String,
        moduleId: String,
        skill: ActivitySkillCategory,
        type: ExerciseTemplateType,
        difficulty: ActivityDifficulty,
        durationMin: Int,
        objective: String,
        instructions: List<String>,
        examples: List<String>,
        promptText: String,
        strategy: EvaluationStrategyType,
        rubric: List<ScoringRubricDimension>,
        nextIds: List<String>,
        permissions: List<ActivityPermission> = emptyList(),
        supportsAudio: Boolean = false,
        supportsVideo: Boolean = false,
        listeningScript: String = "",
        targetPhrase: String = "",
        dialogueOpening: String = "",
        dialogueRole: String = "",
        checklist: List<String> = emptyList(),
        warmupCues: List<String> = emptyList(),
        honestyCaveat: String = ""
    ): ActivityDefinition = ActivityDefinition(
        activityId = id,
        title = title,
        description = description,
        moduleId = moduleId,
        skillCategory = skill,
        exerciseType = type,
        difficulty = difficulty,
        duration = durationMin,
        learningObjective = objective,
        instructions = instructions,
        examples = examples,
        requiredPermissions = permissions,
        interactionConfiguration = InteractionConfiguration(
            promptText = promptText,
            supportsAudioRecording = supportsAudio,
            supportsVideoRecording = supportsVideo,
            supportsTextInput = true,
            listeningScript = listeningScript,
            targetWordOrPhrase = targetPhrase,
            dialogueOpeningLine = dialogueOpening,
            dialoguePartnerRole = dialogueRole,
            checklistItems = checklist,
            warmupCues = warmupCues
        ),
        evaluationConfiguration = EvaluationConfiguration(
            strategy = strategy,
            aiEnabled = true,
            focusCriteria = rubric.map { it.label },
            honestyCaveat = honestyCaveat
        ),
        scoringRubric = rubric,
        completionCriteria = CompletionCriteria(
            minDurationSeconds = if (supportsAudio || supportsVideo) 10 else 5,
            minWordsOrTurns = if (type == ExerciseTemplateType.BREATHING_VOCAL_WARMUP) 3 else 8,
            requiresRecording = false,
            requiresChecklistCompletion = checklist.isNotEmpty() && type == ExerciseTemplateType.BREATHING_VOCAL_WARMUP,
            passingScoreThreshold = 60
        ),
        feedbackConfiguration = defaultFeedback,
        nextActivityIds = nextIds,
        sourceAttribution = "SpeakCraft Core Curriculum",
        contentVersion = 1
    )

